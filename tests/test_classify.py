class TestVocabularyLoad:
    def test_missing_files_warn_but_load(self, tmp_path, caplog):
        with caplog.at_level(logging.WARNING, logger="loganalyzer.classify"):
            vocab = Vocabulary.load(tmp_path)
        assert vocab.entries == []
        assert vocab.build_map == {}
        missing = " ".join(caplog.messages)
        for name in ("android.yaml", "ios.yaml", "ios-builds.yaml", "semantics.yaml"):
            assert name in missing
        # classifier still constructs and runs against an empty vocabulary
        m = Matcher(vocab)
        rec = android_rec("07-03 23:36:43.936 DEBUG [Foo bar] hello world")
        klass = m.classify(rec, None)
        assert klass.status == "unknown"
        assert rec.klass is klass

    def test_fixture_vocab_parses(self, vocab_dir):
        vocab = Vocabulary.load(vocab_dir)
        platforms = {e.platform for e in vocab.entries}
        assert platforms == {ANDROID, IOS}
        assert len(vocab.entries) == len(ANDROID_YAML["entries"]) + len(IOS_YAML["entries"])
        # build map keys/values coerced to str
        assert vocab.build_map["388"] == "4.4.2"
        assert all(isinstance(k, str) and isinstance(v, str) for k, v in vocab.build_map.items())

    def test_real_semantics_layer_loads(self):
        # android.yaml/ios.yaml may or may not exist yet (harvested in
        # parallel) — semantics.yaml is committed and must load.
        vocab = Vocabulary.load(REAL_VOCAB_DIR)
        assert vocab.semantics.get("icon_semantics")
        assert vocab.semantics.get("categories")
        m = Matcher(vocab)
        rec = android_rec(
            "07-03 23:36:44.211 DEBUG [TSGeofenceManager evaluate] evaluate IGNORED"
        )
        klass = m.classify(rec, "4.2.1")
        assert klass.category == "geofence"


# ── Version helpers ──────────────────────────────────────────────────────────

class TestVersioning:
    def test_ver_tuple(self):
        assert _ver_tuple("4.2.1") == (4, 2, 1)
        assert _ver_tuple("4.2.1 (4063)") == (4, 2, 1)
        assert _ver_tuple(None) is None
        assert _ver_tuple("garbage") is None

    def test_in_range_inclusive_and_padded(self):
        assert _in_range((4, 5, 0), _ver_tuple("4.0.0"), _ver_tuple("4.5.0"))
        assert not _in_range((4, 5, 1), _ver_tuple("4.0.0"), _ver_tuple("4.5.0"))
        assert _in_range((4, 5), _ver_tuple("4.5.0"), None)      # (4,5) == (4,5,0)
        assert _in_range(None, _ver_tuple("4.0.0"), _ver_tuple("4.1.0"))  # unknown = no filter


# ── Literal fragment extraction ──────────────────────────────────────────────

class TestLiteralFragments:
    def test_plain_fragments_with_groups(self):
        frags = dict(_literal_fragments(r"Starting timer: ([\d.]+)s repeating: (\d)"))
        assert frags["Starting timer: "] is True
        assert frags["s repeating: "] is True

    def test_escaped_metachars_are_literal(self):
        frags = dict(_literal_fragments(r"isMoving: (.*?) \| stateChanged: "))
        assert frags["isMoving: "] is True
        assert frags[" | stateChanged: "] is True

    def test_alternation_marks_unsafe(self):
        frags = dict(_literal_fragments(r"prefix (ENTER|EXIT) suffix"))
        assert frags["prefix "] is True
        assert frags[" suffix"] is True
        assert frags["ENTER"] is False
        assert frags["EXIT"] is False

    def test_optional_group_and_quantified_char_unsafe(self):
        frags = dict(_literal_fragments(r"head (tail)? end{2} zz"))
        assert frags["head "] is True
        assert frags["tail"] is False       # (…)? is optional
        assert frags[" en"] is True         # the quantified 'd' is dropped
        assert frags[" zz"] is True


