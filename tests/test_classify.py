class TestThroughput:
    def test_classifies_10k_records_per_second(self, synthetic_matcher, synthetic_records):
        t0 = time.perf_counter()
        for rec in synthetic_records:
            synthetic_matcher.classify(rec, "4.5.0")
        elapsed = time.perf_counter() - t0
        rate = len(synthetic_records) / elapsed

        matched = sum(1 for r in synthetic_records if r.klass.status == "matched")
        assert matched == len(synthetic_records)      # the benchmark measures real matching
